#!/usr/bin/env bash
# Generates .env from .credential.txt so that no secret is hardcoded in source control.
# Usage: ./scripts/gen-env.sh
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CRED_FILE="${CRED_FILE:-$ROOT_DIR/.credential.txt}"
ENV_FILE="$ROOT_DIR/.env"
DB_HOST="${DB_HOST:-postgres-15}"
DB_PORT="${DB_PORT:-5432}"
API_PORT="${API_PORT:-3001}"
WEB_PORT="${WEB_PORT:-3000}"
UPLOAD_DIR="${UPLOAD_DIR:-/app/uploads}"
APP_TIMEZONE="${APP_TIMEZONE:-Asia/Jakarta}"
ALLOWED_ORIGINS="${ALLOWED_ORIGINS:-https://bilmary.my.id}"

# JWT_SECRET hanya boleh di-regenerate kalau memang belum ada - kalau berubah,
# semua sesi admin yang sedang login ikut logout.
if [ -f "$ENV_FILE" ]; then
  EXISTING_JWT_SECRET="$(node "$ROOT_DIR/scripts/parse-credential.js" "$ENV_FILE" JWT_SECRET)"
fi
JWT_SECRET="${JWT_SECRET:-${EXISTING_JWT_SECRET:-}}"
if [ -z "$JWT_SECRET" ]; then
  JWT_SECRET="$(node -e 'process.stdout.write(require("node:crypto").randomBytes(48).toString("base64url"))')"
  echo "JWT_SECRET baru dibuat (disimpan di .env, jangan di-commit)."
fi

[ -f "$CRED_FILE" ] || { echo "ERROR: credential file not found: $CRED_FILE" >&2; exit 1; }

read_cred() { node "$ROOT_DIR/scripts/parse-credential.js" "$CRED_FILE" "$1"; }

DB_NAME="$(read_cred 'db')"
DB_USER="$(read_cred 'user db')"
DB_PASS="$(read_cred 'pass db')"

[ -n "$DB_NAME" ] && [ -n "$DB_USER" ] && [ -n "$DB_PASS" ] \
  || { echo "ERROR: could not parse db credentials from $CRED_FILE" >&2; exit 1; }

# Password is URL-encoded to keep the connection string valid.
DB_PASS_ENC="$(node -e 'process.stdout.write(encodeURIComponent(process.argv[1]))' "$DB_PASS")"
DATABASE_URL="postgresql://${DB_USER}:${DB_PASS_ENC}@${DB_HOST}:${DB_PORT}/${DB_NAME}?schema=public&connection_limit=10"

umask 077
# Catatan: kredensial Telegram SENGAJA tidak ditulis ke .env.
# Sumbernya adalah tabel `settings` (telegram.botToken & telegram.chatId).
# Untuk mengisi/memperbarui nilainya: ./scripts/sync-telegram-settings.sh
cat > "$ENV_FILE" <<EOF
# GENERATED by scripts/gen-env.sh from .credential.txt - DO NOT COMMIT
DATABASE_URL="$DATABASE_URL"
APP_TIMEZONE=$APP_TIMEZONE
ALLOWED_ORIGINS=$ALLOWED_ORIGINS
DB_HOST=$DB_HOST
DB_PORT=$DB_PORT
DB_NAME=$DB_NAME
DB_USER=$DB_USER
DB_PASSWORD="$DB_PASS"
JWT_SECRET="$JWT_SECRET"
API_PORT=$API_PORT
WEB_PORT=$WEB_PORT
UPLOAD_DIR=$UPLOAD_DIR
MAX_UPLOAD_MB=10
EOF

chmod 600 "$ENV_FILE"
echo "Wrote $ENV_FILE (mode 600) - keep it out of git."
